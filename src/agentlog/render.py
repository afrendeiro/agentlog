"""Render the log as Markdown in the data dir: LOG.md (by day) and projects/<project>.md."""

import re
from collections import defaultdict
from datetime import datetime

from .common import DATA_DIR


def fmt_min(m: float) -> str:
    m = round(m)
    return f"{m // 60}h{m % 60:02d}m" if m >= 60 else f"{m}m"


def slug(project: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", project).strip("_") or "unnamed"


def entry(r: dict, *, with_project: bool, with_date: bool = False) -> list[str]:
    start, end = datetime.fromisoformat(r["start"]), datetime.fromisoformat(r["end"])
    multi_day = end.date() != start.date()
    when = start.strftime("%Y-%m-%d %H:%M" if with_date else "%m-%d %H:%M" if multi_day else "%H:%M")
    when += "–" + end.strftime("%m-%d %H:%M" if multi_day else "%H:%M")
    s = r.get("summary") or {}
    head = f"**{r['project']}** · " if with_project else ""
    head += f"{when} · {fmt_min(r['active_min'])} active{' total' if multi_day else ''} · {r['harness']}"
    lines = [f"- {head} · {s.get('title') or r.get('title') or r['first_prompt'][:80]}"]
    if s:
        lines += [f"  - before: {s['before']}", f"  - did: {s['did']}", f"  - after: {s['after']}"]
    elif r.get("recap"):
        lines += [f"  - after: {r['recap']}"]
    return lines


def render(records: dict[str, dict]) -> None:
    rows = sorted(records.values(), key=lambda r: r["start"])
    by_day: dict[str, list[dict]] = defaultdict(list)
    by_project: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        for day in r["days"] or [r["start"][:10]]:
            by_day[day].append(r)
        by_project[r["project"]].append(r)

    out = ["# Agent session log", "", "Generated by `agentlog`; edit sessions.jsonl, not this file.", ""]
    out += ["## Projects", "", "| project | sessions | active | last |", "|---|---|---|---|"]
    for p, rs in sorted(by_project.items(), key=lambda kv: max(r["end"] for r in kv[1]), reverse=True):
        total = sum(r["active_min"] for r in rs)
        out.append(
            f"| [{p}](projects/{slug(p)}.md) | {len(rs)} | {fmt_min(total)} | {max(r['end'] for r in rs)[:10]} |"
        )
    for day in sorted(by_day, reverse=True):
        total = sum(r["days"].get(day, 0) for r in by_day[day])
        out += ["", f"## {datetime.fromisoformat(day):%Y-%m-%d %a} · {fmt_min(total)}", ""]
        for r in by_day[day]:
            if r["days"] and day != max(r["days"]):
                # Multi-day session: the full entry is under its last day.
                title = (r.get("summary") or {}).get("title") or r.get("title") or r["first_prompt"][:80]
                out.append(
                    f"- **{r['project']}** · {fmt_min(r['days'][day])} active · {r['harness']} · {title} "
                    f"(session continues until {r['end'][:10]})"
                )
            else:
                out += entry(r, with_project=True)
    (DATA_DIR / "LOG.md").write_text("\n".join(out) + "\n")

    pdir = DATA_DIR / "projects"
    pdir.mkdir(parents=True, exist_ok=True)
    wanted = {f"{slug(p)}.md" for p in by_project}
    for f in pdir.glob("*.md"):
        if f.name not in wanted:
            f.unlink()
    for p, rs in by_project.items():
        total = sum(r["active_min"] for r in rs)
        out = [f"# {p}", "", f"`{rs[-1]['path']}` · {len(rs)} sessions · {fmt_min(total)} active", ""]
        for r in rs:
            out += entry(r, with_project=False, with_date=True)
        (pdir / f"{slug(p)}.md").write_text("\n".join(out) + "\n")
